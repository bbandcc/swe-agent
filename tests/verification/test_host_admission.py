class DispatchAdmissionTests(unittest.TestCase):
    def setUp(self):
        # The closed fixture admits source bytes, not newly generated bytecode.
        # Freeze this ambient input before ReviewedVerificationInputs is built.
        environment = patch.dict(os.environ, {"PYTHONDONTWRITEBYTECODE": "1"})
        environment.start()
        self.addCleanup(environment.stop)

    def _editing_fixture(self, root, marker):
        # A real pytest producer imports app. The marker is outside the admitted
        # inventory so counting executions does not itself mutate source inputs.
        source = (
            "from pathlib import Path\n"
            f"p = Path({str(marker)!r})\n"
            "p.write_text((p.read_text() if p.exists() else '') + 'x')\n"
            "import app\n"
            "def test_value():\n    assert app.value == 1\n"
        ).encode()
        (root / "test_fixed.py").write_bytes(source)
        (root / "app.py").write_bytes(b"value = 1\n")
        spec = VerificationSpec(
            "fixed", (sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider",
                      "--assert=plain", "test_fixed.py", "--junitxml=report.xml"),
            report_path="report.xml",
        )
        return spec, source

    def test_real_editor_post_and_repair_recheck_current_bytes(self):
        for allow_first_post in (False, True):
            with self.subTest(repair=allow_first_post), tempfile.TemporaryDirectory() as directory:
                root = Path(directory) / "workspace"
                root.mkdir()
                marker = Path(directory) / "dispatches.txt"
                spec, test_bytes = self._editing_fixture(root, marker)
                runner = VerificationRunner(root)
                reviewed = ReviewedVerificationInputs(
                    workspace_root=root, runner=runner, specs=(spec,),
                    file_versions={
                        "test_fixed.py": test_bytes,
                        "app.py": (b"value = 1\n", b"value = 0\n")
                        if allow_first_post else b"value = 1\n",
                    },
                )
                edits = iter((("value = 1", "value = 0"), ("value = 0", "value = 2")))
                child = developer(root, lambda _: search_replace(*next(edits)))
                with workspace_root_scope(root):
                    result = create_workflow_graph(
                        architect=lambda _: {"implementation_plan": plan()},
                        developer=child, verification_specs=(spec,),
                        verification_runner=runner, reviewed_inputs=reviewed,
                        workspace_root=root,
                    ).compile().invoke({})
                self.assertEqual(marker.read_text(), "xx" if allow_first_post else "x")
                self.assertEqual(result["repair_attempts"], int(allow_first_post))
                self.assertEqual((root / "app.py").read_bytes(),
                                 b"value = 2\n" if allow_first_post else b"value = 0\n")
                self.assertEqual(result["outcome"], WorkflowOutcome.FAILED)
                self.assertFalse(result["acceptance"].accepted)
                self.assertEqual(result["post_verification"][0].status,
                                 VerificationCheckStatus.EXECUTION_ERROR)
                self.assertIn("not started", result["post_verification"][0].message)
                self.assertFalse((root / "report.xml").exists())

    def test_each_spec_needs_its_own_approval(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory) / "workspace"
            root.mkdir()
            marker = Path(directory) / "dispatches.txt"
            first, source = self._editing_fixture(root, marker)
            second = VerificationSpec("different-check", first.argv, report_path="report.xml")
            runner = VerificationRunner(root)
            reviewed = ReviewedVerificationInputs(
                workspace_root=root, runner=runner, specs=(first,),
                file_versions={"test_fixed.py": source, "app.py": b"value = 1\n"},
            )
            result = VerificationController(
                (first, second), runner, root, reviewed_inputs=reviewed,
            ).run_baseline(AgentState())
            self.assertEqual(marker.read_text(), "x")
            self.assertEqual([r.status for r in result["baseline_verification"]],
                             [VerificationCheckStatus.PASS, VerificationCheckStatus.EXECUTION_ERROR])
            self.assertEqual(result["outcome"], WorkflowOutcome.FAILED)

    def test_explicit_runner_without_proof_is_not_admitted(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            marker = root / "sentinel.txt"
            spec = VerificationSpec("sentinel", (sys.executable, "-c",
                                    "from pathlib import Path; Path('sentinel.txt').touch()"))
            result = VerificationController((spec,), VerificationRunner(root), root).run_baseline(AgentState())
            self.assertFalse(marker.exists())
            self.assertEqual(result["baseline_verification"][0].status, VerificationCheckStatus.EXECUTION_ERROR)

    def test_new_config_environment_file_or_runner_root_invalidates_proof(self):
        for change in ("environment", "new-file", "root", "spec"):
            with self.subTest(change=change), tempfile.TemporaryDirectory() as directory:
                root = Path(directory) / "workspace"
                root.mkdir()
                marker = Path(directory) / "dispatches.txt"
                spec, source = self._editing_fixture(root, marker)
                runner = VerificationRunner(root)
                reviewed = ReviewedVerificationInputs(
                    workspace_root=root, runner=runner, specs=(spec,),
                    file_versions={"test_fixed.py": source, "app.py": b"value = 1\n"},
                )
                with patch.dict(os.environ):
                    if change == "environment":
                        os.environ["PYTEST_ADDOPTS"] = "--collect-only"
                    elif change == "new-file":
                        (root / "conftest.py").write_bytes(b"# newly supplied plugin\n")
                    elif change == "root":
                        # A new actual runner boundary cannot reuse the old proof.
                        runner = VerificationRunner(Path(directory))
                    else:
                        spec = VerificationSpec("changed", spec.argv, report_path="report.xml")
                    result = VerificationController((spec,), runner, root, reviewed_inputs=reviewed).run_baseline(AgentState())
                self.assertFalse(marker.exists())
                self.assertEqual(result["baseline_verification"][0].status, VerificationCheckStatus.EXECUTION_ERROR)

    def test_default_non_durable_production_graph_denies_without_import_failure(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            checks = json.dumps([{"name": "sentinel", "argv": [sys.executable, "-c",
                                "from pathlib import Path; Path('sentinel.txt').touch()"]}])
            with workspace_root_scope(root), patch.dict(os.environ, {"SWE_AGENT_VERIFICATION_CHECKS": checks}):
                result = create_production_workflow_graph(
                    architect=lambda _: {},
                    developer=lambda _: self.fail("baseline refusal must stop editing"),
                ).compile().invoke({})
            self.assertFalse((root / "sentinel.txt").exists())
            self.assertEqual(result["outcome"], WorkflowOutcome.FAILED)


class DurableAdmissionTests(RunConfigTestCase):
    def test_real_cli_start_resume_default_durable_denies_and_audits(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            spec = VerificationSpec("sentinel", (sys.executable, "-c",
                                    "from pathlib import Path; Path('sentinel.txt').touch()"))
            config = self.make_config(root, verification_specs=(spec,), max_cost_usd=None)
            revision = AgentCodeRevision("a" * 40, AgentRevisionStatus.KNOWN)
            with (
                patch("agent.runtime.__main__.load_run_config", return_value=config),
                patch("agent.runtime.__main__.detect_agent_code_revision", return_value=revision),
                patch("agent.runtime.durable.create_architect_workflow", return_value=lambda _: {}),
                patch("agent.runtime.durable.create_developer_workflow", return_value=lambda _: self.fail("refused baseline")),
            ):
                for command in ("start", "resume"):
                    output = io.StringIO()
                    args = [command, "--run-id", "admission-run", "--thread-id", "admission-thread", "--task-id", "admission-task"]
                    if command == "start":
                        args += ["--task", "controlled fixture"]
                    with redirect_stdout(output):
                        code = main(args)
                    summary = json.loads(output.getvalue())
                    self.assertNotEqual(code, 0)
                    self.assertEqual(summary["workflow_outcome"], "failed")
                    self.assertFalse(summary["acceptance"]["accepted"])
                    self.assertTrue(summary["record_ref"])
            self.assertFalse((config.workspace_root / "sentinel.txt").exists())
            self.assertTrue(any(config.runtime_root.rglob("*.sqlite*")))

    def test_resume_new_post_requires_new_admission_but_keeps_recorded_baseline(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            config = self.make_config(root, verification_specs=(VerificationSpec("fixed", ("pytest", "--junitxml=report.xml")),), max_cost_usd=None)
            request = recovery.VerificationRecoveryTests()._request(config)
            from tests.runtime.test_verification_recovery import MarkerRunner, _graph_factory
            runner = MarkerRunner(root)
            started = start_run(config, request, {}, graph_factory=_graph_factory(
                runner=runner, interrupt_after=("finish_baseline_verification",)), clock=lambda: 100.0)
            self.assertEqual(started.status.value, "paused")
            self.assertEqual((root / "fixed.count").read_text(), "1")

            def no_proof(current, _run_id, saver, clock):
                return create_workflow_graph(
                    architect=lambda _: {}, developer=lambda _: {"developer_status": DeveloperStatus.COMPLETED},
                    verification_specs=current.verification_specs, verification_runner=VerificationRunner(current.workspace_root),
                    workspace_root=current.workspace_root, durable_runtime=True, clock=clock,
                ).compile(checkpointer=saver)

            resumed = resume_run(config, ResumeRequest(request.identity, request.run_config_digest, request.agent_revision),
                                 graph_factory=no_proof, clock=lambda: 150.0)
            self.assertEqual((root / "fixed.count").read_text(), "1")
            self.assertEqual(resumed.state["baseline_verification"][0].status, VerificationCheckStatus.PASS)
            self.assertEqual(resumed.state["post_verification"][0].status, VerificationCheckStatus.EXECUTION_ERROR)
            self.assertFalse(resumed.state["acceptance"].accepted)
